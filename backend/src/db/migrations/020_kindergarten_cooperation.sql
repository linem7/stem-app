-- 020 · 园所加一列「起始合作日期」
--
-- 起因（2026-08-22 用户提）：园所列表要能看到「什么时候开始合作的」。
--
-- 【为什么不用 created_at 顶替】
-- created_at 是**这一行什么时候被导进库的**，不是合作什么时候开始的。
-- 早期几个园是先谈成、过了两三个月我才建的行；批量导入的那六个更是
-- 同一秒建的，而它们的合作起始日各不相同。
-- 用 created_at 当合作起始日，得到的是一个**看起来完全正常的错数**——
-- 「这个园合作多久了」正是这一列存在的唯一理由，而它会答错。
--
-- 【为什么是 DATE 不是 TIMESTAMPTZ】
-- 合作是按天谈的（「9 月 1 号开始」），没有时刻。存 timestamptz 会引入时区，
-- 于是「9 月 1 日」在某些时区的展示里变成 8 月 31 日。
--
-- 【为什么可空】
-- 库里已有的园一个都没有这个日期，而我不知道它们真实的起始日 ——
-- 猜一个填进去就是编数据。空 = 「不知道」，界面上显示「—」。
--
-- 【它跟 note 的关系】
-- note 那一列的注释写着「备注：合作起止、联系人等」—— 合作起止本来是塞在
-- 自由文本里的。塞在 note 里的日期排不了序、筛不了、也统计不出来
-- 「今年新签了几个园」。这一列把它从一句话变成一个数据。
-- **note 里已有的那些话不动**（历史备注还有别的内容）。
-- ============================================================

ALTER TABLE kindergartens
  ADD COLUMN IF NOT EXISTS cooperation_started_at DATE;

COMMENT ON COLUMN kindergartens.cooperation_started_at IS
  '起始合作日期。跟 created_at 不是一回事：created_at 是这一行被导进库的时刻，
   而这一列是合作真正开始的那一天，由人填。可空（＝不知道），
   界面上显示「—」，不要拿 created_at 兜底。';
