-- ============================================================
-- 009 · 兑换码可以不绑手机号
--
-- 起因：原来的模型是「一人一码」—— 问卷星导出答卷，按手机号一个个建码。
-- 二十个老师就要建二十次，而且每次都要把手机号姓名抄一遍。
-- 2026-08-18 用户改成：**直接建一批匿名码**，谁拿到谁能兑，
-- 导出 CSV 灌进问卷星当奖励发，或者整批交给园所。
--
-- 代价必须写下来：**「问卷答卷 ↔ 小程序账号」的对应关系不在这个库里了**。
-- 它在问卷星那边（哪个手机号领到了哪个码）。所以：
--   · 后台按手机号搜不到这批老师 —— 改成按兑换码搜（老师列表已带上她兑的码）
--   · 「一个手机号只激活一个账号」这道防线对匿名码天然不成立，
--     真正的防线变成「一个码只能兑一次」
--
-- 仍然可以建绑定码（填了手机号就是老规矩，含查重），两种并存。
-- ============================================================

ALTER TABLE redemption_codes ALTER COLUMN phone     DROP NOT NULL;
ALTER TABLE redemption_codes ALTER COLUMN real_name DROP NOT NULL;

COMMENT ON COLUMN redemption_codes.phone IS
  '绑定码填手机号（激活时写进 teachers.phone 并查重）；匿名码为空 —— 谁拿到谁能兑';
