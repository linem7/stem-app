-- 018 · 老师档案补两项：最高学历、职称
--
-- 起因（用户 2026-08-21）：「我的」页那个档案要挪到「我的记忆」下面
-- 当第一条（不参与编号），涵盖六项 —— 园所、年级、岗位、最高学历、职称、教龄。
-- 前四项里只有「最高学历」和「职称」库里没有，这次加上。
--
-- 【为什么这两项值得存】
-- 它们不是装饰性的档案字段，是**这个研究项目要分析的自变量**：
-- 「AI 写的教案对新手老师和对一级教师，帮助是不是同一回事」——
-- 教龄答不了这个问题（教龄长不等于职称高），学历也答不了。
-- 三个一起才描述得出「她是什么水平的从业者」。
--
-- 【为什么不是枚举类型而是 varchar】
-- 大陆幼儿园教师职称序列 2022 年后并进中小学序列（三级/二级/一级/高级/正高级），
-- 而各省落地节奏不一样，园所内部还有「园聘」这类叫法。
-- 用 PG 的 enum，以后加一档要写迁移；varchar + 应用层白名单，
-- 改一个数组就行。白名单在 `services/roster.js` 旁边（POSITIONS 同一处）。
--
-- 【隐私】这两项和教龄同级：**关于老师这个从业者的，不是关于任何一个孩子的**，
-- 所以不触碰「不存幼儿任何信息」那条红线。
-- 但它们跟 real_name 不同级 —— 学历职称**可以下发前端**（是她自己填的、她自己要看），
-- 姓名不行。别顺手把它们塞进同一个「敏感字段」清单里一起屏蔽掉。
--
-- 【为什么可空、且没有默认值】
-- 已激活的老师一个都没填过。给默认值（比如 '未评'）等于替她声明了一件事，
-- 而「没填」和「评过但是最低档」在研究上是两回事。
-- ============================================================

ALTER TABLE teachers
  ADD COLUMN IF NOT EXISTS education VARCHAR(32),
  ADD COLUMN IF NOT EXISTS professional_title VARCHAR(32);

COMMENT ON COLUMN teachers.education IS
  '最高学历。白名单见 services/roster.js 的 EDUCATIONS：
   中专及以下 / 大专 / 本科 / 硕士及以上。老师自己填，可以为空（＝没填过）。';

COMMENT ON COLUMN teachers.professional_title IS
  '职称。白名单见 services/roster.js 的 TITLES：
   未评定 / 三级教师 / 二级教师 / 一级教师 / 高级教师 / 正高级教师。
   ⚠️ 「未评定」是一个她主动选的值，跟 NULL（没填过）不是一回事 ——
   研究上要分得开，所以不要在应用层把 NULL 显示成「未评定」。';
