-- ============================================================
-- 024 · 出生年份 → 出生年月
--
-- 起因（2026-09-21 用户定）：完善信息那一项要收「出生年月」而不是「出生年」，
-- 输入框提示语是「如 1995-12」。
--
-- 【为什么不加一列 birth_month，而是换掉 birth_year】
-- 加一列的话会有「只填了年、没填月」的中间状态，而那个状态**没有意义** ——
-- 这个界面上一填就是年月一起填（同一个输入框）。多一列就多一种
-- 「两列对不上」的可能（month 有值但 year 是 NULL），而那种行没有任何用途。
--
-- 【为什么存成 VARCHAR(7) 而不是 DATE】
-- `DATE` 会带上「日」，而日是不收的 —— 存成 `1995-12-01` 会让
-- 「她生日是 12 月 1 日」这个**不存在的信息**看起来像是收上来了。
-- 这个项目在「不存幼儿信息」「只收姓氏」那几处都是同一个立场：
-- **不收的东西不要以任何形式进入库里**，哪怕是补一个默认值。
--
--   `VARCHAR(7)` 存 `'1995-12'`：
--     · 长度固定 7，不用 CHECK 也基本不会写歪（多一道 CHECK 见下面）
--     · 排序、比较都跟字面一致（'1995-12' > '1995-01'），要分年度
--       `LEFT(birth_month, 4)` 就够
--
-- ⚠️ 023 加的那一列 `birth_year` **直接丢掉**，不做数据迁移 ——
-- 023 是今天（同一天）才上的，而且生产库上**一行都没填过**
-- （完善信息那个功能刚做完、还没人用过）。留着它只会让下一个人
-- 以为「有两个出生时间字段，该用哪个」。
-- ============================================================

ALTER TABLE teachers DROP COLUMN IF EXISTS birth_year;

ALTER TABLE teachers ADD COLUMN IF NOT EXISTS birth_month VARCHAR(7);

/* 格式约束：`YYYY-MM`。
   ⚠️ 用 `~` 正则而不是 `LIKE` —— `LIKE '____-__'` 会放过 `abcd-ef`。
   月份限定 01–12，年份限定 19xx/20xx（现在在岗的老师不会更早）。 */
ALTER TABLE teachers DROP CONSTRAINT IF EXISTS teachers_birth_month_check;
ALTER TABLE teachers ADD CONSTRAINT teachers_birth_month_check
  CHECK (birth_month IS NULL OR birth_month ~ '^(19|20)[0-9]{2}-(0[1-9]|1[0-2])$');

COMMENT ON COLUMN teachers.birth_month IS
  '出生年月，格式 YYYY-MM（如 1995-12）。**她主动填的**（完善信息那一步），
   不是 AI 推断的 —— 这跟记忆抽取那条「不提取年龄」的红线不冲突，
   那条管的是从对话里自动抽取。
   ⚠️ 刻意不存日期：不收的东西不该以任何形式进库，哪怕是补一个默认的「01」。';
