-- ============================================================
-- 017 · 学习模式：同一条链路，多告诉她「为什么」
--
-- 起因：现在这套的基本逻辑是「老师说一句话 → 答 4 题 → AI 直接给教案」。
-- 它提升的是**撰写效率**，但老师的专业素养和独立写教案的能力没有变化 ——
-- 用一年之后她还是不会自己写。而这是一个合作研究项目，
-- 「老师有没有成长」比「她今天省了多少时间」更接近它的目的。
--
-- 所以加一个模式。**它不是另一条链路**：出题、生成、改稿、配图全部照旧，
-- 只是沿途多解释「为什么问这个」「为什么这样设计」。
-- 这条约束是硬的 —— 分叉出第二条生成链路，两边就会慢慢长得不一样，
-- 而两条里总有一条是没人测的。
--
-- 【为什么挂在会话上，不挂在老师身上】
-- 她可能这份想快（明天就要上）、下一份想学（周末有空）。
-- 挂在老师身上就变成了一个「设置」，而她要的是每次都能选。
-- 界面上默认沿用上次选的那个（存本机，见 frontend/src/stores/prefs.js），
-- 所以「每次都能选」不等于「每次都要选」。
--
-- 【为什么默认 efficient】
-- 已有的会话全部是效率模式产出的，默认值必须让它们保持原样 ——
-- 否则历史教案会突然被当成学习模式的，去找不存在的解读。
--
-- 【额度】不额外收（用户 2026-08-20 定）：学习模式比效率模式多 1-2 次
-- 模型调用，成本差几分钱。多收会惩罚正是这个项目想鼓励的行为。
-- 所以这里**没有**额度相关的列 —— 闸门那边一个字都不用改。
-- ============================================================

ALTER TABLE conversations
  ADD COLUMN IF NOT EXISTS mode VARCHAR(16) NOT NULL DEFAULT 'efficient';

COMMENT ON COLUMN conversations.mode IS
  'efficient（效率模式，默认）| learning（学习模式）。
   只影响「沿途解释多少」：learning 时引导页每题带一句「为什么问这个」，
   成稿页每个板块下可展开一段教案解读（content_json.commentary）。
   出题、生成、改稿、配图的链路完全相同 —— 不许按 mode 分叉出第二条实现。';

-- 教案库要按模式筛（内测时最想看的对照就是「学习模式的老师是不是改稿改得更少」），
-- 而 mode 的取值只有两个、分布很可能极不均匀，所以只对 learning 建部分索引：
-- 全表索引在这种基数下选择性太差，规划器多半不会用。
CREATE INDEX IF NOT EXISTS idx_conversations_learning
  ON conversations (teacher_id, created_at DESC)
  WHERE mode = 'learning' AND deleted_at IS NULL;
